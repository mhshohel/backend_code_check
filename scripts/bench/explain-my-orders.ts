// Measures the "my orders" keyset query before and after migration 0002.
// "Before" swaps the composite index for the single-column index that
// migration 0001 created, runs the measurements, and then restores 0002.
// Usage: DATABASE_URL=postgresql://...ofl_bench tsx scripts/bench/explain-my-orders.ts
import { writeFileSync } from 'node:fs';
import pg from 'pg';
import { hardwareDescription, percentile } from './load';

// The same SQL and parameter shape as listOrders() in
// packages/server-core/src/features/orders/queries.ts (customer, no filters).
const MY_ORDERS_SQL = `
  SELECT o.id, o.number, o.status, o.total_minor, o.created_at
  FROM orders o
  WHERE ($1::uuid IS NULL OR o.customer_id = $1)
    AND ($2::text[] IS NULL OR o.status = ANY($2::text[]))
    AND ($3::uuid IS NULL OR EXISTS (
          SELECT 1 FROM reservations r WHERE r.order_id = o.id AND r.warehouse_id = $3 AND r.status = 'CONFIRMED'))
    AND (NOT $4::boolean OR EXISTS (SELECT 1 FROM returns rt WHERE rt.order_id = o.id AND rt.status = 'REQUESTED'))
    AND ($5::timestamptz IS NULL OR (o.created_at, o.id) < ($5::timestamptz, $6::uuid))
  ORDER BY o.created_at DESC, o.id DESC
  LIMIT $7`;

const RUNS = 30;

type Measurement = { label: string; plan: string; p50: number; p95: number };

const client = new pg.Client({ connectionString: process.env.DATABASE_URL });
await client.connect();

async function heaviestCustomer(): Promise<{ id: string; orders: number }> {
  const result = await client.query<{ id: string; orders: string }>(
    'SELECT customer_id AS id, count(*) AS orders FROM orders GROUP BY 1 ORDER BY 2 DESC LIMIT 1',
  );
  const row = result.rows[0];
  if (!row) throw new Error('No orders. Load the bench profile first.');
  return { id: row.id, orders: Number(row.orders) };
}

/** A cursor deep in the customer's history: the 2001st newest order. */
async function deepCursor(customerId: string): Promise<{ createdAt: string; id: string }> {
  const result = await client.query<{ created_at: Date; id: string }>(
    'SELECT created_at, id FROM orders WHERE customer_id = $1 ORDER BY created_at DESC, id DESC OFFSET 2000 LIMIT 1',
    [customerId],
  );
  const row = result.rows[0];
  if (!row) throw new Error('Customer has fewer than 2001 orders.');
  return { createdAt: row.created_at.toISOString(), id: row.id };
}

async function measure(label: string, params: unknown[]): Promise<Measurement> {
  const explain = await client.query<{ 'QUERY PLAN': string }>(`EXPLAIN (ANALYZE, BUFFERS) ${MY_ORDERS_SQL}`, params);
  const plan = explain.rows.map((row) => row['QUERY PLAN']).join('\n');
  const timings: number[] = [];
  for (let run = 0; run < RUNS; run++) {
    const result = await client.query<{ 'QUERY PLAN': Array<{ 'Execution Time': number }> }>(
      `EXPLAIN (ANALYZE, FORMAT JSON) ${MY_ORDERS_SQL}`,
      params,
    );
    timings.push(result.rows[0]?.['QUERY PLAN'][0]?.['Execution Time'] ?? Number.NaN);
  }
  timings.sort((a, b) => a - b);
  return { label, plan, p50: percentile(timings, 50), p95: percentile(timings, 95) };
}

async function useBeforeIndexes(): Promise<void> {
  await client.query('CREATE INDEX IF NOT EXISTS orders_customer_id_idx ON orders (customer_id)');
  await client.query('DROP INDEX IF EXISTS orders_customer_created_idx');
  await client.query('ANALYZE orders');
}

async function useAfterIndexes(): Promise<void> {
  await client.query('CREATE INDEX IF NOT EXISTS orders_customer_created_idx ON orders (customer_id, created_at DESC, id DESC)');
  await client.query('DROP INDEX IF EXISTS orders_customer_id_idx');
  await client.query('ANALYZE orders');
}

try {
  const customer = await heaviestCustomer();
  const cursor = await deepCursor(customer.id);
  const totalOrders = Number((await client.query<{ n: string }>('SELECT count(*) AS n FROM orders')).rows[0]?.n);
  const firstPage = [customer.id, null, null, false, null, null, 21];
  const deepPage = [customer.id, null, null, false, cursor.createdAt, cursor.id, 21];

  await useBeforeIndexes();
  const before = [await measure('before: first page', firstPage), await measure('before: page after 2000 orders', deepPage)];
  await useAfterIndexes();
  const after = [await measure('after: first page', firstPage), await measure('after: page after 2000 orders', deepPage)];

  const rows = [...before, ...after]
    .map((m) => `| ${m.label} | ${m.p50.toFixed(3)} | ${m.p95.toFixed(3)} |`)
    .join('\n');
  const plans = [...before, ...after].map((m) => `### ${m.label}\n\n\`\`\`\n${m.plan}\n\`\`\``).join('\n\n');
  const report = `# "My orders" query: before and after migration 0002

Generated by \`scripts/bench/explain-my-orders.ts\` on ${new Date().toISOString()}.

- Hardware: ${hardwareDescription()}
- PostgreSQL: ${(await client.query<{ v: string }>("SELECT current_setting('server_version') AS v")).rows[0]?.v}
- Dataset: ${totalOrders} orders; measured customer has ${customer.orders} orders.
- Query: page size 20 (+1 row for hasNextPage). ${RUNS} runs each; times are PostgreSQL execution time in ms.
- Before: \`orders_customer_id_idx (customer_id)\`. After: \`orders_customer_created_idx (customer_id, created_at DESC, id DESC)\`.

| Case | p50 ms | p95 ms |
| --- | --- | --- |
${rows}

## Plans

${plans}
`;
  writeFileSync(new URL('../../reports/explain-my-orders.md', import.meta.url), report);
  console.warn(rows);
} finally {
  await client.end();
}
