// Writes the SDL into a TypeScript module. Bundlers (Turbopack, esbuild, Vite)
// then carry the schema as code, and no runtime path to contracts/ is needed.
import { readFileSync, writeFileSync } from 'node:fs';

const sdl = readFileSync(new URL('../../../contracts/schema.graphql', import.meta.url), 'utf8');
const output = `// Generated by scripts/embed-schema.ts from contracts/schema.graphql. Do not edit.\nexport const schemaSDL = ${JSON.stringify(sdl)};\n`;
writeFileSync(new URL('../src/generated/schema-sdl.ts', import.meta.url), output);
